using System;
using Assets.Scripts.Craft.Parts;
using ModApi.GameLoop;
using ModApi.GameLoop.Interfaces;
using UnityEngine;

namespace KomplexHeat
{
    /// <summary>
    /// Represents the base class for heat sources within the KomplexHeat framework.
    /// This abstract class provides core functionality for managing heat transfer
    /// behavior during flight within the game. Subclasses must implement specific
    /// properties and behaviors to define the heat source characteristics.
    /// </summary>
    public abstract class HeatSourceBase : MonoBehaviourBase, IFlightStart, IFlightFixedUpdate, IFlightFixedUpdateWarp
    {
        private const float PartSpecificHeat = 921f; // hardcoded in DragPhysics.CalculateConvectionHeat

        /// <summary>
        /// The areal density of a part's aluminum wall in kg/m^2. Derived with these parameters:
        /// 1. An empty 1 m^3 cube fuel tank in JNO is 75 kg.
        /// 2. It has a surface area of 6 m^2.
        /// 3. Its areal density is therefore 75 kg / 6 m^2 = 12.5 kg/m^2.
        /// </summary>
        private const float ArealDensity = 12.5f;

        /// <summary>
        /// The game's "scaled mass" is for the purpose of floating precision, but this mod operates
        /// in SI units, which uses kg.
        /// </summary>
        private const float MassScaleInv = ModApi.Constants.MassScaleInv;

        private HeatCore _heatCore;
        private bool _initialized;
        private PartScript _partScript;
        private float _surfaceArea;

        /// <summary>
        /// See <see cref="HeatCore.SpecificHeat"/> for how this default const is derived.
        /// </summary>
        protected virtual float HeatCoreSpecificHeat => 897f;

        /// <summary>
        /// The conduction interface area between the HeatCore and the part's skin, in m^2.
        /// Defaults to a hollow-shell approximation: mass divided by areal density. This works
        /// for thin-walled parts. Dense/solid heat cores should override this.
        /// </summary>
        /// <param name="partMassDry">The part's dry mass in kg</param>
        /// <returns>The conduction interface area in m^2</returns>
        protected virtual float GetSurfaceArea(float partMassDry) => Mathf.Max(partMassDry / ArealDensity, 0f);

        /// <summary>
        /// Heat transfer coefficient of the interface between the HeatCore and the part's skin in
        /// W/(m^2 K).
        /// </summary>
        protected abstract float HeatTransferCoefficient { get; }

        /// <summary>
        /// The thermal mass of the HeatCore in kg.
        /// </summary>
        protected abstract float GetHeatCoreThermalMass(float partMassDry);

        /// <summary>
        /// The heat flow rate from the core to the part's skin in the last tick, in watts.
        /// Positive means heat is flowing from core to skin.
        /// </summary>
        public float HeatFlowRate { get; private set; }

        /// <summary>
        /// Gets the total rate of heat generated by this source during the current simulation tick,
        /// in watts. The value is reset at the beginning of each tick and accumulates each call to
        /// <see cref="GenerateHeat"/>.
        /// </summary>
        public float HeatGenerationRate { get; private set; }

        void IFlightFixedUpdate.FlightFixedUpdate(in FlightFrameData frame) => Tick(frame);
        void IFlightFixedUpdateWarp.FlightFixedUpdateWarp(in FlightFrameData frame) => Tick(frame);


        void IFlightStart.FlightStart(in FlightFrameData frame)
        {
            _partScript = GetComponentInParent<PartScript>();
            if (_partScript is null) return;

            // Resolve subclass reference first because GetSurfaceArea and GetHeatCoreThermalMass
            // may depend on them.
            if (!OnFlightStart(_partScript)) return;

            var partMassDry = _partScript.Data.PartMass.Dry * MassScaleInv;

            // There is no direct way to get the surface area of a part, so it is approximated
            // by assuming the part is a hollow cube.
            _surfaceArea = GetSurfaceArea(partMassDry);

            _heatCore = gameObject.AddComponent<HeatCore>();
            _heatCore.SpecificHeat = HeatCoreSpecificHeat;
            _heatCore.ThermalMass = GetHeatCoreThermalMass(partMassDry);
            _heatCore.Temperature = _partScript.Temperature;

            _initialized = true;
        }

        /// <summary>
        /// Resolves subclass references needed by <see cref="GetSurfaceArea"/> and
        /// <see cref="GetHeatCoreThermalMass"/>. Called before the heat core exists, so
        /// implementations must not call <see cref="GenerateHeat"/> or otherwise use the core.
        /// </summary>
        /// <returns>Is this source applicable to the part and should be initialized.</returns>
        protected abstract bool OnFlightStart(PartScript partScript);

        protected abstract void ApplyHeat();

        /// <summary>
        /// A human-readable identifier for the host part for use in logging.
        /// </summary>
        protected string PartDescription => _partScript == null
            ? "an unknown part"
            : $"{_partScript.Data.Name} [ID {_partScript.Data.Id}]";

        /// <summary>
        /// Adds heat generated by this source to the core.
        /// </summary>
        /// <param name="watts">The rate of heat to generate in watts.</param>
        protected void GenerateHeat(float watts)
        {
            if (_heatCore == null)
            {
                throw new InvalidOperationException(
                    $"{nameof(GenerateHeat)} called before the heat core was initialized on {PartDescription}");
            }

            _heatCore.AddHeatPower(watts);
            HeatGenerationRate += watts;
        }

        private void Tick(in FlightFrameData frame)
        {
            if (!_initialized) return;
            HeatGenerationRate = 0f;
            ApplyHeat();
            ApplyConduction(frame);
        }

        /// <summary>
        /// Applies Newton's law of cooling to the HeatCore and the part.
        /// </summary>
        private void ApplyConduction(in FlightFrameData frame)
        {
            var dt = (float)frame.DeltaTimeWorld;
            if (dt <= 0) return;

            // C is heat capacity.
            var heatCoreC = _heatCore.ThermalMass * _heatCore.SpecificHeat;
            var partThermalMass = _partScript.ThermalMass * MassScaleInv;
            var partSkinC = partThermalMass * PartSpecificHeat;

            // Formula from https://en.wikipedia.org/wiki/Newton%27s_law_of_cooling#Mathematical_formulation
            var flux = HeatTransferCoefficient * (_heatCore.Temperature - _partScript.Temperature);
            HeatFlowRate = flux * _surfaceArea;

            // If part heat capacity is invalid, the equilibrium temperature is a meaningless value,
            // so the flow rate cap is not enforced.
            if (partSkinC > 0)
            {
                var totalHeat = heatCoreC * _heatCore.Temperature + partSkinC * _partScript.Temperature;
                var equilibriumTemperature = totalHeat / (heatCoreC + partSkinC);
                var maxHeatFlowRateFromCore =
                    Mathf.Abs((_heatCore.Temperature - equilibriumTemperature) * heatCoreC / dt);
                var maxHeatFlowRateFromPart =
                    Mathf.Abs((_partScript.Temperature - equilibriumTemperature) * partSkinC / dt);
                var maxHeatFlowRate = Mathf.Min(maxHeatFlowRateFromCore, maxHeatFlowRateFromPart);
                HeatFlowRate = Mathf.Clamp(HeatFlowRate, -maxHeatFlowRate, maxHeatFlowRate);
            }

            // Allow the HeatCore to lose heat even if the part has no thermal mass, so tinkered
            // parts with invalid thermal mass don't get an infinitely hot HeatCore.
            _heatCore.AddHeatPower(-HeatFlowRate);

            if (partSkinC <= 0) return; // guard against divide by 0 or negative number.
            _partScript.Temperature += HeatFlowRate * dt / partSkinC;
        }
    }
}